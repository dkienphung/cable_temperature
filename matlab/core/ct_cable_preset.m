function c = ct_cable_preset(name)
%CT_CABLE_PRESET  Cables of the paper.
%   'cable70'  : Table 1/2, Barrinax U-1000 R2V 1x70 mm2 (XLPE/PVC), ambient 19 degC
%   'cable150' : Table 3/4, H07RN-F TITANEX 1x150 mm2 (paper's XLPE/PVC curves used)
%   Site elevation 280 m (Terrassa laboratory, not stated in the paper).
switch lower(name)
    case {'cable70', '70'}
        c = ct_cable('name', 'cable70', 'designation', 'Barrinax U-1000 R2V 1x70 mm2 (0.6/1 kV, XLPE/PVC)', ...
            'conductor_diameter', 9.5e-3, 'insulation_thickness', 1.1e-3, 'jacket_thickness', 1.5e-3, ...
            'effective_cross_section', 70e-6, 'resistivity_T0', 1.85e-8, 'alpha', 0.0043, ...
            'conductor_mass_per_length', 0.584, 'ambient_temperature', 19, 'elevation', 280, ...
            'test_steps', [120 1950; 145 1950; 170 1500; 185 1850; 212 1350]);
    case {'cable150', '150'}
        c = ct_cable('name', 'cable150', 'designation', 'H07RN-F TITANEX 1x150 mm2', ...
            'conductor_diameter', 15e-3, 'insulation_thickness', 2.0e-3, 'jacket_thickness', 2.5e-3, ...
            'effective_cross_section', 150e-6, 'resistivity_T0', 1.85e-8, 'alpha', 0.0043, ...
            'conductor_mass_per_length', 1.74, 'ambient_temperature', 23.5, 'elevation', 280, ...
            'test_steps', [130 766; 163 554; 220 850; 305 530; 405 400]);
    otherwise
        error('ct_cable_preset:name', 'unknown cable %s (cable70 | cable150)', name);
end
end
