function c = ct_cable(varargin)
%CT_CABLE  Cable / wire description (same fields as the Python CableSpec).
%   c = ct_cable('name', value, ...).  Geometry: D1 = conductor diameter, D2 = D1 + 2 t_ins,
%   D3 = D2 + 2 t_jac (paper Fig. 1).  Derived quantities: see ct_cable_geometry.
c = struct('name', '', 'designation', '', ...
    'conductor_diameter', NaN, 'insulation_thickness', NaN, 'jacket_thickness', NaN, ...
    'effective_cross_section', NaN, 'resistivity_T0', NaN, 'alpha', NaN, 'T0', 20, ...
    'conductor_mass_per_length', NaN, ...
    'conductor_material', ct_material('copper'), 'insulation_material', ct_material('xlpe'), ...
    'jacket_material', ct_material('pvc'), 'emissivity', 0.85, 'ambient_temperature', 20, ...
    'elevation', 0, 'test_steps', zeros(0, 2), 'max_continuous_temperature', 90, ...
    'short_circuit_temperature', 250);
for i = 1:2:numel(varargin)
    if ~isfield(c, varargin{i}), error('ct_cable:field', 'unknown field %s', varargin{i}); end
    c.(varargin{i}) = varargin{i + 1};
end
end
